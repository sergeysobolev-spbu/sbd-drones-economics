"""
Константы топиков для SystemBus (единая шина для систем и компонентов).

Политика: 1 топик = 1 система/компонент.
Маршрутизация по полю "action" внутри сообщения.
"""


# ============================================================================
# Топики для систем (systems)
# ============================================================================

class SystemTopics:
    """Топики для межсистемного взаимодействия."""

    DUMMY = "systems.dummy"

    @classmethod
    def all(cls) -> list:
        """Возвращает список всех системных топиков."""
        return [cls.DUMMY]


# ============================================================================
# Топики для компонентов (components)
# ============================================================================

class ComponentTopics:
    """Топики для компонентов дрона."""

    DUMMY_COMPONENT = "components.dummy_component"

    @classmethod
    def all(cls) -> list:
        """Возвращает список всех топиков компонентов."""
        return [cls.DUMMY_COMPONENT]


# ============================================================================
# Actions для dummy системы
# ============================================================================

class DummyActions:
    """Действия для dummy системы."""
    ECHO = "echo"
    PROCESS = "process"
    RESPONSE = "response"


# ============================================================================
# Actions для dummy компонента
# ============================================================================

class DummyComponentActions:
    """Действия для dummy компонента."""
    ECHO = "echo"
    INCREMENT = "increment"
    GET_STATE = "get_state"
